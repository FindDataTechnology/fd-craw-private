// platform-preset-bridge.js — the platform profile's SDK JSON-RPC server.
//
// Subclasses the stock @deepseek-ai/dsh-sdk-jsonrpc-server plugin to add the
// three things the platform host needs that the stock server does not carry:
//
//   1. `initialize` accepts `agentPreset` (the deployment-selected agent mode).
//   2. Lazily-created sessions compose that preset: `createSession` calls
//      `agents.create` itself (duplicating the parent's ~8-line call) with a
//      `setup(agentCtx)` hook that runs `agentPresets.mount(agentCtx, id)` —
//      the one supported mount call site, so a broken or unknown preset fails
//      session creation BEFORE the agent is published (the factory rolls the
//      whole creation back). The preset id is also recorded on the session
//      header (`meta.agentPreset`) so the session's log names the composition
//      it started with. No roster composed → session creation is delegated to
//      the parent unchanged (bare host composition).
//   3. A `presets/list` JSON-RPC method returns the serialized roster
//      (id/name/description/trust/broken) for the web picker.
//
// Loaded by presets.patch.yml (generated by the host's dsh-profile.js), which
// disables the stock `sdk-jsonrpc-server` row and inserts this plugin under a
// fresh row id. Its imports resolve through the profile's node_modules walk
// (the profile pins dsh-agent-presets; dsh-sdk-jsonrpc-server is linked there)
// — except dsh-sdk-protocol, which ships as a PRIVATE dependency of the SDK
// server package, so it is resolved through that package's real location.

import { createRequire } from "node:module";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import Schema from "@deepseek-ai/schemastery";
import { SessionId } from "@deepseek-ai/dsh-session";
import { HarnessSdkJsonRpcServer } from "@deepseek-ai/dsh-sdk-jsonrpc-server";

// JsonRpcLineTransport lives in the SDK server package's own dependency
// closure. Re-anchor resolution at the server package's entry file (its real
// path — Node resolves symlinks), where the protocol package is reachable.
const transport = await (async () => {
  const serverRequire = createRequire(
    import.meta.resolve("@deepseek-ai/dsh-sdk-jsonrpc-server"),
  );
  const protocolDir = join(
    serverRequire.resolve("@deepseek-ai/dsh-sdk-protocol/package.json"),
    "..",
  );
  return import(pathToFileURL(join(protocolDir, "lib", "index.js")));
})();
const { JsonRpcLineTransport } = transport;

const name = "platform-sdk-server";
const inject = ["agents"];
const Config = Schema.object({ maxTokensAsSuccess: Schema.boolean().default(false) });

class PlatformSdkServer extends HarnessSdkJsonRpcServer {
  agentPresetId = null;

  async initialize(params) {
    this.agentPresetId =
      typeof params?.agentPreset === "string" && params.agentPreset
        ? params.agentPreset
        : null;
    return super.initialize(params);
  }

  async createSession(sessionId) {
    const presets = this.ctx.get("agentPresets");
    if (presets === undefined) return super.createSession(sessionId);
    // Resolve before creation so an unknown id fails before any session or
    // agent state exists; mount in setup so a broken composition rolls the
    // whole creation back instead of publishing a half-composed agent.
    const preset = await presets.resolve(this.agentPresetId ?? undefined);
    const rec = {
      handle: await this.ctx.agents.create({
        sessionId: SessionId(sessionId),
        meta: { cwd: this.cwd, agentPreset: preset.id },
        agentOptions: {
          provider: this.provider,
          model: this.model,
          ...(this.maxTokens === undefined ? {} : { maxTokens: this.maxTokens }),
        },
        setup: async (agentCtx) => {
          await presets.mount(agentCtx, preset.id);
        },
      }),
    };
    this.sessions.set(sessionId, rec);
    return rec;
  }

  async handleRequest(method, params) {
    if (method === "presets/list") {
      const presets = this.ctx.get("agentPresets");
      if (presets === undefined) return [];
      const rows = await presets.list();
      return rows.map((p) => ({
        id: p.id,
        name: p.name ?? p.id,
        description: p.description ?? "",
        trust: p.trust,
        ...(p.broken === undefined ? {} : { broken: p.broken }),
      }));
    }
    return super.handleRequest(method, params);
  }
}

// Wiring identical to the stock plugin's apply — the only change is the server
// class. Stdout stays reserved for protocol frames; `shutdown` disposes the
// SDK-created agents and exits 0.
function apply(ctx, config) {
  const resolvedConfig = config;
  const rootFiber = ctx.root.fiber;
  const input = config.input ?? process.stdin;
  const output = config.output ?? process.stdout;
  const exit = config.exit ?? ((code) => process.exit(code));
  const transportPeer = new JsonRpcLineTransport(input, output);
  const server = new PlatformSdkServer(ctx, transportPeer, {
    maxTokensAsSuccess: resolvedConfig.maxTokensAsSuccess,
  });
  let exitTask;
  const disposeAndExit = () => {
    exitTask ??= (async () => {
      await Promise.allSettled([Promise.resolve().then(() => transportPeer.flush())]);
      await Promise.allSettled([Promise.resolve().then(() => rootFiber.dispose())]);
      exit(0);
    })();
    return exitTask;
  };
  transportPeer.onRequest(async (method, params) => {
    const result = await server.handleRequest(method, params);
    if (method === "shutdown") {
      setImmediate(() => disposeAndExit());
    }
    return result;
  });
  ctx.effect(() => {
    transportPeer.start();
    return async () => {
      await server.shutdown();
      transportPeer.close();
    };
  }, "jsonrpc.serve");
}

export { Config, PlatformSdkServer, apply, inject, name };
